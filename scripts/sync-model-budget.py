"""Export the cached workbook values for the static 3D viewer (read-only XLSX)."""
import json
from pathlib import Path
from openpyxl import load_workbook

root = Path(__file__).resolve().parents[1]
source = root / 'docs/referencias/orcamento_cabeamento_ti_connect.xlsx'
workbook = load_workbook(source, data_only=True)
items = []
for row in workbook['Orçamento'].iter_rows(min_row=14, values_only=True):
    if row[0] not in ('Equipamentos', 'Cabeamento', 'Terminações', 'Montagem'):
        continue
    items.append(dict(id=len(items)+1, group=row[0], name=row[1], quantity=row[2], unit=row[3], model=row[8]))
floors = []
for name in ('Térreo', '1º andar', '2º andar', '3º andar'):
    sheet = workbook[name]
    allocations = [dict(id=row[0], quantity=row[3], unit=row[4]) for row in sheet.iter_rows(min_row=7, values_only=True) if isinstance(row[0], int)]
    floors.append(dict(name=name, total=sheet['G4'].value, items=allocations))
data = dict(source=str(source.relative_to(root)), total=workbook['Orçamento']['B9'].value, items=items, floors=floors)
assert items and all(isinstance(floor['total'], (int, float)) for floor in floors), 'Save calculated workbook values before exporting'
assert isinstance(data['total'], (int, float)) and abs(sum(floor['total'] for floor in floors) - data['total']) < 0.01, 'Floor totals do not reconcile'
(root / 'budget-data.mjs').write_text('// Generated by scripts/sync-model-budget.py from the principal workbook.\nexport const budget = '+json.dumps(data, ensure_ascii=False, indent=2)+';\n')
print(f'Exported {len(items)} items, {len(floors)} floors; total {data["total"]:.2f}')
